use super::db::Database;
use base64::{engine::general_purpose::STANDARD as base64, Engine as _};
use std::time::{Duration, SystemTime, UNIX_EPOCH};
use tauri::{AppHandle, Emitter, Manager};

struct ClipboardSnapshot {
    content: String,
    content_type: String,
    file_size: Option<i32>,
    image_width: Option<i32>,
    image_height: Option<i32>,
    source_app: String,
}

/// M-cb1：已知密码管理器源 app 名（不区分大小写匹配）。
/// 这些 app 复制密码时未必设置 org.nspasteboard.ConcealedType marker，
/// 故按源 app 名兜底过滤，避免明文密码入库。
const PASSWORD_MANAGER_APPS: &[&str] = &[
    "1password",
    "1password 7",
    "1password 8",
    "bitwarden",
    "keepassxc",
    "keepassx",
    "dashlane",
    "lastpass",
    "enpass",
    "keeper",
    "robiform",
    "nordpass",
];

/// 启发式判定：内容本身像 secret（独立长 token / password= 赋值等）。
/// 保守策略——只拦截明显的 secret 形态，避免误伤正常代码/长串。
fn looks_like_secret(text: &str) -> bool {
    let trimmed = text.trim();
    if trimmed.is_empty() {
        return false;
    }
    // 明显赋值形式：password= / passwd= / pwd= / secret= / token= / api_key=
    let lower = trimmed.to_ascii_lowercase();
    for prefix in [
        "password:",
        "password=",
        "passwd:",
        "passwd=",
        "pwd:",
        "pwd=",
        "secret:",
        "secret=",
        "token:",
        "token=",
        "api_key:",
        "api_key=",
    ] {
        if lower.starts_with(prefix) && trimmed.len() > prefix.len() + 3 {
            return true;
        }
    }
    // 私钥 PEM 头
    if trimmed.contains("-----BEGIN ") && trimmed.contains("PRIVATE KEY-----") {
        return true;
    }
    // 长 base64-ish / hex 串（≥40 字符，仅含 [A-Za-z0-9+/=]）— 接近通用 secret 形态
    if trimmed.len() >= 40
        && trimmed
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '+' || c == '/' || c == '=')
    {
        return true;
    }
    false
}

fn is_password_manager(app_name: &str) -> bool {
    let lower = app_name.to_ascii_lowercase();
    PASSWORD_MANAGER_APPS
        .iter()
        .any(|&name| lower == name || lower.contains(name))
}

pub fn start_monitor(app_handle: AppHandle) {
    std::thread::spawn(move || {
        let mut last_change_count: isize = 0;

        loop {
            std::thread::sleep(Duration::from_millis(500));

            let (tx, rx) = std::sync::mpsc::channel::<(isize, Option<ClipboardSnapshot>)>();

            let _ = app_handle.run_on_main_thread(move || {
                use crate::platform::pasteboard;
                use objc2_app_kit::NSWorkspace;

                let change_count = pasteboard::change_count();

                let snapshot = (|| -> Option<ClipboardSnapshot> {
                    if change_count == last_change_count {
                        return None;
                    }

                    // 跳过自身 marker + transient/concealed/auto_gen（通过 platform::pasteboard）
                    if pasteboard::has_type("com.litiantao.voidnix.clipboard")
                        || pasteboard::has_type("org.nspasteboard.TransientType")
                        || pasteboard::has_type("org.nspasteboard.ConcealedType")
                        || pasteboard::has_type("org.nspasteboard.AutoGeneratedType")
                    {
                        return None;
                    }

                    let mut content = String::new();
                    let mut content_type = String::new();
                    let mut file_size: Option<i32> = None;
                    let mut image_width: Option<i32> = None;
                    let mut image_height: Option<i32> = None;

                    // file URL / PNG 走 platform::pasteboard（不再直访 NSPasteboard）
                    if let Some(s) = pasteboard::read_file_url() {
                        content = s;
                        content_type = "file".to_string();
                        let path = content.strip_prefix("file://").unwrap_or(&content);
                        let decoded_path = percent_decode(path);
                        if let Ok(meta) = std::fs::metadata(&decoded_path) {
                            file_size = Some(meta.len().min(i32::MAX as u64) as i32);
                        }
                    } else if let Some(text) = pasteboard::read_text() {
                        let text = text.trim().to_string();
                        if text.is_empty() {
                            return None;
                        }

                        let is_all_emoji = text.chars().all(|c| {
                            let cp = c as u32;
                            (0x1F300..=0x1FAFF).contains(&cp)
                                || (0x2600..=0x27BF).contains(&cp)
                                || (0xFE00..=0xFE0F).contains(&cp)
                        });

                        if is_all_emoji {
                            return None;
                        }

                        content = text;
                        content_type = "text".to_string();
                    } else if let Some(slice) = pasteboard::read_png() {
                        let len = slice.len();
                        if len > 0 {
                            file_size = Some((len as u64).min(i32::MAX as u64) as i32);
                            if len >= 24 && slice[0..4] == [0x89, 0x50, 0x4E, 0x47] {
                                image_width =
                                    Some(u32::from_be_bytes(slice[16..20].try_into().unwrap())
                                        as i32);
                                image_height =
                                    Some(u32::from_be_bytes(slice[20..24].try_into().unwrap())
                                        as i32);
                            }
                            content = format!("data:image/png;base64,{}", base64.encode(&slice));
                            content_type = "image".to_string();
                        }
                    }

                    if content.is_empty() {
                        return None;
                    }

                    let mut source_app = String::from("Unknown");
                    let ws = NSWorkspace::sharedWorkspace();
                    if let Some(app) = ws.frontmostApplication() {
                        if let Some(name) = app.localizedName() {
                            source_app = name.to_string();
                        }
                    }

                    // M-cb1：密码管理器源 / 内容像 secret → 不入库（明文密码不入 SQLite）
                    // ConcealedType marker 是第一道防线，此处为兜底（部分密码管理器不设 marker）
                    if content_type == "text"
                        && (is_password_manager(&source_app) || looks_like_secret(&content))
                    {
                        return None;
                    }

                    Some(ClipboardSnapshot {
                        content,
                        content_type,
                        file_size,
                        image_width,
                        image_height,
                        source_app,
                    })
                })();

                let _ = tx.send((change_count, snapshot));
            });

            let Ok((new_change_count, snap)) = rx.recv() else {
                continue;
            };

            if new_change_count == last_change_count {
                continue;
            }
            last_change_count = new_change_count;

            let Some(snap) = snap else {
                continue;
            };

            let db = app_handle.state::<Database>();
            let conn = db.conn();

            let last_content: Option<String> = conn
                .prepare("SELECT content FROM clipboard_history ORDER BY created_at DESC LIMIT 1")
                .ok()
                .and_then(|mut stmt| stmt.query_row([], |row| row.get(0)).ok());

            if let Some(last) = last_content {
                if last == snap.content {
                    continue;
                }
            }

            let existing_items: Vec<bool> = conn
                .prepare("SELECT is_favorite FROM clipboard_history WHERE content = ?1")
                .map(|mut stmt| {
                    stmt.query_map(rusqlite::params![snap.content], |row| row.get(0))
                        .map(|rows| rows.filter_map(|r| r.ok()).collect())
                        .unwrap_or_default()
                })
                .unwrap_or_default();

            let is_favorite = existing_items.iter().any(|&fav| fav);

            if !existing_items.is_empty() {
                let _ = conn.execute(
                    "UPDATE clipboard_history SET created_at = datetime('now'), source_app = ?2, file_size = ?3, image_width = ?4, image_height = ?5 WHERE content = ?1",
                    rusqlite::params![snap.content, snap.source_app, snap.file_size, snap.image_width, snap.image_height],
                );
                if is_favorite {
                    let _ = conn.execute(
                        "UPDATE clipboard_history SET is_favorite = 1 WHERE content = ?1",
                        rusqlite::params![snap.content],
                    );
                }
            } else {
                let id = format!(
                    "{}",
                    SystemTime::now()
                        .duration_since(UNIX_EPOCH)
                        .unwrap()
                        .as_millis()
                );

                let _ = conn.execute(
                    "INSERT INTO clipboard_history (id, content, content_type, source_app, is_favorite, file_size, image_width, image_height) VALUES (?1, ?2, ?3, ?4, ?5, ?6, ?7, ?8)",
                    rusqlite::params![id, snap.content, snap.content_type, snap.source_app, is_favorite, snap.file_size, snap.image_width, snap.image_height],
                );
            }

            use tauri_plugin_store::StoreExt;
            let store = app_handle.store("extensions/clipboard/config.json");
            let mut max_days: i32 = 30;

            if let Ok(s) = store {
                if let Some(n) = s.get("maxDays").and_then(|v| v.as_i64()) {
                    max_days = n as i32;
                }
            }

            const MAX_ROWS: i64 = 5000;

            if max_days > 0 {
                let _ = conn.execute(
                    "DELETE FROM clipboard_history WHERE is_favorite = 0 AND created_at < datetime('now', ?1)",
                    rusqlite::params![format!("-{} days", max_days)],
                );
            } else {
                let count: i64 = conn
                    .query_row("SELECT COUNT(*) FROM clipboard_history", [], |row| {
                        row.get(0)
                    })
                    .unwrap_or(0);
                if count > MAX_ROWS {
                    let _ = conn.execute(
                        "DELETE FROM clipboard_history WHERE is_favorite = 0 AND created_at < (SELECT MIN(created_at) FROM (SELECT created_at FROM clipboard_history ORDER BY created_at DESC LIMIT ?1))",
                        rusqlite::params![MAX_ROWS],
                    );
                }
            }

            let _ = app_handle.emit("clipboard-updated", ());
        }
    });
}

fn percent_decode(s: &str) -> String {
    let mut result = Vec::new();
    let bytes = s.as_bytes();
    let mut i = 0;
    while i < bytes.len() {
        if bytes[i] == b'%' && i + 2 < bytes.len() {
            if let Ok(byte) =
                u8::from_str_radix(std::str::from_utf8(&bytes[i + 1..i + 3]).unwrap_or(""), 16)
            {
                result.push(byte);
                i += 3;
                continue;
            }
        }
        result.push(bytes[i]);
        i += 1;
    }
    String::from_utf8_lossy(&result).into_owned()
}
