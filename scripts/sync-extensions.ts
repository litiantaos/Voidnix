#!/usr/bin/env bun
// 扫描 extensions/*/native/mod.rs：
//   - `pub fn init()` 签名 → configure_app! 的 .plugin() 链
//   - 各 init() 的 invoke_handler(generate_handler![...]) 命令 → 全局 generate_handler! 列表
// 生成 extensions.rs：configure_app! 含 .plugin() 链 + .invoke_handler(全局所有命令)。
//
// 命令注册边界（§2.8 v1.9 修正）：
//   - 所有 #[tauri::command]（框架 + 扩展）在 configure_app! 的单一 generate_handler! 全局注册。
//     前端用裸名 invoke('cmd')。插件 invoke_handler 不注册命令（Tauri 2 插件命令需
//     'plugin:name|cmd' 格式，裸名只路由全局，故扩展命令必须全局注册）。
//   - 各 init() 仅保留 plugin::Builder 的 .setup（命令执行依赖的 State）。
//
// 另含 windowViews 漂移校验（v1.5 A4）：声明 windowViews 槽的扩展，每个 key 必须在
// tauri.conf.json 的 windows[].label 中存在；以 `-` 或 `*` 结尾的 key 视为动态窗口前缀
// （如 `pin-` 匹配运行时创建的 `pin-<id>`），跳过精确匹配。
import { readdirSync, readFileSync, writeFileSync, existsSync, statSync } from 'node:fs'
import { join, relative } from 'node:path'

const ROOT = process.cwd()
const EXT_DIR = join(ROOT, 'extensions')
const OUT_FILE = join(ROOT, 'src-tauri', 'src', 'extensions.rs')
const CONF_FILE = join(ROOT, 'src-tauri', 'tauri.conf.json')

const INIT_REGEX = /^pub\s+fn\s+init\s*\(/m
const COMMAND_ATTR = /^#\[\s*tauri::command/
const FN_NAME = /(?:pub\s+)?(?:async\s+)?fn\s+(\w+)/
const rustName = (id: string) => id.replace(/-/g, '_')

// 框架命令固定列表（lib.rs 自管，不扫描）。扩展命令由 scanExtensionCommands 扫描。
const FRAMEWORK_COMMANDS = [
  'crate::runtime::permission::check_screen_recording_permission',
  'crate::runtime::permission::check_accessibility_permission',
  'crate::runtime::permission::request_accessibility_permission',
  'crate::runtime::permission::check_full_disk_access_permission',
  'crate::runtime::permission::open_privacy_settings',
  'crate::runtime::shortcut::start_shortcut_recording',
  'crate::runtime::shortcut::stop_shortcut_recording',
  'crate::runtime::shortcut::is_app_active',
  'crate::runtime::shortcut::hide_window',
  'crate::runtime::shortcut::register_global_shortcut',
  'crate::runtime::window::get_home_dir',
  'crate::runtime::window::pick_directory',
  'crate::platform::pasteboard::pasteboard_write_text',
]

function scanInitExtensions(): string[] {
  const ids: string[] = []
  for (const dir of readdirSync(EXT_DIR)) {
    const modPath = join(EXT_DIR, dir, 'native', 'mod.rs')
    if (!existsSync(modPath)) continue // 纯 TS 扩展无 native
    const src = readFileSync(modPath, 'utf8')
    if (INIT_REGEX.test(src)) ids.push(dir)
  }
  return ids.sort()
}

/** 递归收集 .rs 文件（排除 src/ 等 binary 目录）。 */
function walkRs(dir: string, out: string[] = [], skip = ['src']): string[] {
  for (const name of readdirSync(dir)) {
    if (skip.includes(name)) continue
    const full = join(dir, name)
    const st = statSync(full)
    if (st.isDirectory()) walkRs(full, out, skip)
    else if (full.endsWith('.rs')) out.push(full)
  }
  return out
}

/** 文件相对 native/ 的路径 → Rust 模块路径（mod.rs 折叠）。 */
function relToModule(rel: string): string {
  const parts = rel
    .replace(/\.rs$/, '')
    .split('/')
    .filter((p) => p !== 'mod')
  return parts.join('::')
}

/** 扫描文件内 #[tauri::command] fn 名（逐行，跳过中间属性）。 */
function scanCommandsInFile(src: string): string[] {
  const cmds: string[] = []
  const lines = src.split('\n')
  let i = 0
  while (i < lines.length) {
    if (COMMAND_ATTR.test(lines[i].trim())) {
      let j = i + 1
      while (j < lines.length && (/^\s*#\[/.test(lines[j]) || lines[j].trim() === '')) j++
      const m = lines[j]?.match(FN_NAME)
      if (m) cmds.push(m[1])
      i = j + 1
    } else {
      i++
    }
  }
  return cmds
}

/** 扫描各扩展 native/ 下 #[tauri::command]，按文件路径推断全局模块路径。 */
function scanExtensionCommands(ids: string[]): string[] {
  const cmds: string[] = []
  for (const id of ids) {
    const nativeDir = join(EXT_DIR, id, 'native')
    for (const file of walkRs(nativeDir)) {
      const src = readFileSync(file, 'utf8')
      const modPath = relToModule(relative(nativeDir, file))
      const prefix = modPath ? `${modPath}::` : ''
      for (const fn of scanCommandsInFile(src)) {
        cmds.push(`crate::extensions::${rustName(id)}::${prefix}${fn}`)
      }
    }
  }
  return cmds.sort()
}

function buildExtensionsRs(ids: string[], extCmds: string[]): string {
  const pluginChain = ids
    .map((id) => `        .plugin(crate::extensions::${rustName(id)}::init())`)
    .join('\n')
  const allCmds = [...FRAMEWORK_COMMANDS, ...extCmds]
  const cmdList = allCmds.map((c) => `            ${c},`).join('\n')
  const modDecls = ids
    .map((id) => `#[path = "../../extensions/${id}/native/mod.rs"]\npub mod ${rustName(id)};`)
    .join('\n\n')
  return `// AUTO-GENERATED by scripts/sync-extensions.ts. DO NOT EDIT.
// configure_app! 含 .plugin() 链 + 全局 invoke_handler（框架 + 扩展命令）。
// 扩展命令全局注册（裸名 invoke），插件 invoke_handler 不注册命令（§2.8 v1.9）。

macro_rules! configure_app {
    ($builder:expr) => {
        $builder
${pluginChain}
            .invoke_handler(tauri::generate_handler![
${cmdList}
            ])
    };
}
pub(crate) use configure_app;

${modDecls}
`
}

const ids = scanInitExtensions()
const extCmds = scanExtensionCommands(ids)
const content = buildExtensionsRs(ids, extCmds)

// windowViews 漂移校验（v1.5 A4）：始终运行（sync 与 --check 模式均校验）
const wvError = checkWindowViews()
if (wvError) {
  console.error(`[sync-extensions] CHECK FAILED: ${wvError}`)
  process.exit(1)
}

if (process.argv.includes('--check')) {
  const existing = existsSync(OUT_FILE) ? readFileSync(OUT_FILE, 'utf8') : ''
  if (existing !== content) {
    console.error(
      '[sync-extensions] CHECK FAILED: extensions.rs is out of date. Run `bun run sync:extensions`.',
    )
    process.exit(1)
  }
  console.log(
    `[sync-extensions] Check passed (${ids.length} extensions, ${FRAMEWORK_COMMANDS.length + extCmds.length} commands).`,
  )
} else {
  writeFileSync(OUT_FILE, content)
  console.log(
    `[sync-extensions] Synced ${ids.length} extensions, ${FRAMEWORK_COMMANDS.length + extCmds.length} commands (${extCmds.length} extension + ${FRAMEWORK_COMMANDS.length} framework)`,
  )
}

/** 提取对象字面量块（从 `windowViews:` 后的 `{` 起到匹配的 `}`），返回块内文本。 */
function extractBlock(src: string, key: string): string | null {
  const idx = src.indexOf(`${key}:`)
  if (idx === -1) return null
  let i = idx + key.length
  while (i < src.length && src[i] !== '{') i++
  if (src[i] !== '{') return null
  let depth = 0
  const start = i + 1
  for (; i < src.length; i++) {
    const c = src[i]
    if (c === '{') depth++
    else if (c === '}') {
      depth--
      if (depth === 0) return src.slice(start, i)
    }
  }
  return null
}

/** 从 windowViews 块提取所有 key（兼容 bare / 单引号 / 双引号）。 */
function extractWindowViewKeys(block: string): string[] {
  const keys: string[] = []
  const re = /(?:'([^']+)'|"([^"]+)"|([A-Za-z_$][\w$]*))\s*:/g
  let m: RegExpExecArray | null
  while ((m = re.exec(block)) !== null) {
    keys.push(m[1] ?? m[2] ?? m[3])
  }
  return keys
}

/** windowViews 漂移校验：返回错误消息（null = 通过）。 */
function checkWindowViews(): string | null {
  if (!existsSync(CONF_FILE)) return null // 配置缺失时不阻塞（由其他校验兜底）
  const conf = JSON.parse(readFileSync(CONF_FILE, 'utf8'))
  const labels = new Set<string>((conf?.app?.windows ?? []).map((w: { label: string }) => w.label))
  if (labels.size === 0) return null

  const violations: string[] = []
  for (const dir of readdirSync(EXT_DIR)) {
    const indexPath = join(EXT_DIR, dir, 'index.ts')
    if (!existsSync(indexPath)) continue
    const src = readFileSync(indexPath, 'utf8')
    const block = extractBlock(src, 'windowViews')
    if (!block) continue
    for (const key of extractWindowViewKeys(block)) {
      // 以 `-` 或 `*` 结尾 = 动态窗口前缀（如 `pin-`/`pin-*`），跳过精确匹配
      if (key.endsWith('-') || key.endsWith('*')) continue
      if (!labels.has(key)) {
        violations.push(
          `extensions/${dir}/index.ts windowViews key '${key}' 不在 tauri.conf.json windows[].label 中`,
        )
      }
    }
  }
  if (violations.length === 0) return null
  return `windowViews 漂移（v1.5 A4）：\n  ${violations.join('\n  ')}`
}
